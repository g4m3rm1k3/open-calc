export function getThemeStyles(themeId, isDarkGlobal) {
  const t = STUDIO_THEMES[themeId] || STUDIO_THEMES.default;
  if (t.dynamic) {
    const isDark = isDarkGlobal;
    return {
      ui: isDark ? t.uiDark : t.uiLight,
      md: isDark ? t.mdDark : t.mdLight,
      monaco: isDark ? t.monacoDark : t.monacoLight,
      isDark
    };
  } else {
    // Same forceLight handling as ThemeContext.jsx's inline computation —
    // keep both in sync; this one bit vue-light identically before the fix.
    const isDark = !t.forceLight;
    return {
      ui: t.uiDark,
      md: t.mdDark,
      monaco: (isDark ? t.monacoDark : t.monacoLight) ?? t.monacoDark ?? t.monacoLight,
      isDark
    };
  }
}
