/**
 * Scans src/practice/*.ts and writes a lightweight manifest (id, title,
 * levelCount) to src/practice/manifest.ts — cheap metadata the loader can
 * import eagerly, so the Practice Explorer's sidebar doesn't need to fetch and
 * evaluate every challenge file's full content just to show a title + badge.
 * Full challenge content stays lazy-loaded per file.
 *
 * Run:  node scripts/build-practice-manifest.mjs
 */

import { readFileSync, readdirSync, writeFileSync } from 'fs'
import { join, dirname, basename } from 'path'
import { fileURLToPath } from 'url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const PRACTICE_DIR = join(ROOT, 'src', 'practice')
const EXCLUDE = new Set(['loader.ts', 'manifest.ts'])

const files = readdirSync(PRACTICE_DIR)
  .filter(f => f.endsWith('.ts') && !EXCLUDE.has(f))

const manifest = files.map(f => {
  const id = basename(f, '.ts')
  const raw = readFileSync(join(PRACTICE_DIR, f), 'utf8')
  const titleMatch = raw.match(/export const title = (['"`])((?:[^\\]|\\.)*?)\1/)
  const levelMatches = raw.match(/level: [123],/g) || []
  return {
    id,
    title: titleMatch ? titleMatch[2] : id,
    levelCount: levelMatches.length,
  }
}).sort((a, b) => a.id.localeCompare(b.id))

const out = `// Auto-generated by scripts/build-practice-manifest.mjs — do not edit by hand
// Practice files: ${manifest.length}

export interface PracticeMeta {
  id: string
  title: string
  levelCount: number
}

export const PRACTICE_MANIFEST: PracticeMeta[] = ${JSON.stringify(manifest, null, 2)}
`

const outPath = join(PRACTICE_DIR, 'manifest.ts')
writeFileSync(outPath, out, 'utf8')
console.log(`Wrote ${outPath} (${manifest.length} practice files)`)
