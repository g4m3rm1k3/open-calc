/**
 * Scans src/concepts/*.md and writes a lightweight manifest (id, name, series,
 * seriesTitle, part) to src/concepts/manifest.ts — cheap metadata the loader can
 * import eagerly, so sidebars/search don't need to fetch and parse a concept's
 * full body just to show its name. Full content stays lazy-loaded per file.
 *
 * Run:  node scripts/build-concept-manifest.mjs
 */

import { readFileSync, readdirSync, writeFileSync } from 'fs'
import { join, dirname, basename } from 'path'
import { fileURLToPath } from 'url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const CONCEPTS_DIR = join(ROOT, 'src', 'concepts')

// Mirrors parseFrontmatter in src/concepts/loader.ts exactly.
function parseFrontmatter(md) {
  const m = md.match(/^---\n([\s\S]*?)\n---\n?/)
  if (!m) return {}
  const meta = {}
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':')
    if (i === -1) continue
    meta[line.slice(0, i).trim()] = line.slice(i + 1).trim()
  }
  return meta
}

const files = readdirSync(CONCEPTS_DIR).filter(f => f.endsWith('.md'))

const manifest = files.map(f => {
  const id = basename(f, '.md')
  const raw = readFileSync(join(CONCEPTS_DIR, f), 'utf8')
  const meta = parseFrontmatter(raw)
  return {
    id,
    name: meta.name || id,
    series: meta.series || null,
    seriesTitle: meta.seriesTitle || null,
    part: meta.part ? parseInt(meta.part, 10) : null,
  }
}).sort((a, b) => a.id.localeCompare(b.id))

const out = `// Auto-generated by scripts/build-concept-manifest.mjs — do not edit by hand
// Concepts: ${manifest.length}

export interface ConceptMeta {
  id: string
  name: string
  series: string | null
  seriesTitle: string | null
  part: number | null
}

export const CONCEPT_MANIFEST: ConceptMeta[] = ${JSON.stringify(manifest, null, 2)}
`

const outPath = join(CONCEPTS_DIR, 'manifest.ts')
writeFileSync(outPath, out, 'utf8')
console.log(`Wrote ${outPath} (${manifest.length} concepts)`)
