/**
 * Scans src/posts recursively for .md files and writes a lightweight manifest (slug, title,
 * excerpt, topics, folderName, readMin) to src/posts/manifest.ts — cheap
 * metadata BlogListPage can import eagerly so it doesn't need to load the
 * full body of every post just to render a list. Full content stays
 * lazy-loaded per post (see BlogPostPage.jsx).
 *
 * Run:  node scripts/build-blog-manifest.mjs
 */

import { readFileSync, readdirSync, writeFileSync } from 'fs'
import { join, dirname, relative, sep } from 'path'
import { fileURLToPath } from 'url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const POSTS_DIR = join(ROOT, 'src', 'posts')

function walk(dir) {
  let out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) out = out.concat(walk(full))
    else if (entry.name.endsWith('.md')) out.push(full)
  }
  return out
}

// Mirrors pathToSlug in BlogListPage.jsx / BlogPostPage.jsx exactly.
function pathToSlug(relPath) {
  return relPath
    .replace(/\.md$/, '')
    .split('/')
    .map(s =>
      s.toLowerCase()
        .replace(/\s+/g, '-')
        .replace(/[^a-z0-9-]/g, '-')
        .replace(/-+/g, '-')
        .replace(/^-|-$/g, '')
    )
    .join('/')
}

function extractMeta(raw, relPath) {
  const slug = pathToSlug(relPath)
  const parts = relPath.replace(/\.md$/, '').split('/')
  const folderName = parts.length > 1 ? parts.slice(0, -1).join('/') : null
  const lines = raw.split('\n')

  const h1 = lines.find(l => l.startsWith('# '))
  const title = h1 ? h1.replace(/^# /, '').trim() : slug.split('/').pop().replace(/-/g, ' ')

  let excerpt = ''
  for (const line of lines) {
    const t = line.trim()
    if (!t || t.startsWith('#') || t.startsWith('---') || t.startsWith('```')) continue
    excerpt = t.length > 220 ? t.slice(0, 220) + '…' : t
    break
  }

  const topics = lines
    .filter(l => l.startsWith('## '))
    .map(l => l.replace(/^## /, '').trim())
    .slice(0, 4)

  const wordCount = raw.split(/\s+/).length
  const readMin = Math.max(1, Math.round(wordCount / 200))

  return { slug, folderName, title, excerpt, topics, readMin, path: `src/posts/${relPath}` }
}

const files = walk(POSTS_DIR)

const manifest = files
  .map(full => {
    const relPath = relative(POSTS_DIR, full).split(sep).join('/')
    const raw = readFileSync(full, 'utf8')
    return extractMeta(raw, relPath)
  })
  .sort((a, b) => a.slug.localeCompare(b.slug))

const out = `// Auto-generated by scripts/build-blog-manifest.mjs — do not edit by hand
// Posts: ${manifest.length}

export interface BlogPostMeta {
  slug: string
  folderName: string | null
  title: string
  excerpt: string
  topics: string[]
  readMin: number
  /** Repo-relative path, e.g. "src/posts/foo.md" — for tooling that needs to write back to the source file. */
  path: string
}

export const BLOG_MANIFEST: BlogPostMeta[] = ${JSON.stringify(manifest, null, 2)}
`

const outPath = join(POSTS_DIR, 'manifest.ts')
writeFileSync(outPath, out, 'utf8')
console.log(`Wrote ${outPath} (${manifest.length} posts)`)
